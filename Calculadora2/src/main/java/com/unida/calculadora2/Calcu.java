public class Calcu {
    public static int Suma(int a, int b){
        return a + b;
    }
    public static int resta(int a, int b){
        return a - b;
    }
    public static int multi(int a, int b){
        return a * b;
    }
    public static int div(int a, int b){
        return a/b;
    }
    
}
